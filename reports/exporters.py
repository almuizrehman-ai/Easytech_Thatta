# PDF EXPORT (ReportLab)
# ============================================================
def generate_pdf_report(rows, report_meta):
    """
    Generate a styled PDF report.

    Returns bytes of PDF.
    """
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import (
        Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle,
    )

    buffer = io.BytesIO()

    # ---------- Document Setup ----------
    doc = SimpleDocTemplate(
        buffer,
        pagesize=landscape(A4),
        leftMargin=15 * mm,
        rightMargin=15 * mm,
        topMargin=15 * mm,
        bottomMargin=15 * mm,
        title=f'{INSTITUTE_NAME} — Collection Report',
        author=INSTITUTE_NAME,
    )

    # ---------- Styles ----------
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        'TitleStyle',
        parent=styles['Title'],
        fontSize=18,
        textColor=colors.HexColor('#0B1736'),
        spaceAfter=2,
        alignment=0,  # left
    )
    subtitle_style = ParagraphStyle(
        'SubtitleStyle',
        parent=styles['Normal'],
        fontSize=10,
        textColor=colors.HexColor('#64748B'),
        spaceAfter=12,
    )
    meta_style = ParagraphStyle(
        'MetaStyle',
        parent=styles['Normal'],
        fontSize=9,
        textColor=colors.HexColor('#475569'),
        spaceAfter=4,
    )
    small_style = ParagraphStyle(
        'SmallStyle',
        parent=styles['Normal'],
        fontSize=7,
        leading=9,
    )
    footer_style = ParagraphStyle(
        'FooterStyle',
        parent=styles['Normal'],
        fontSize=8,
        textColor=colors.HexColor('#94A3B8'),
        alignment=1,  # center
    )

    # ---------- Header ----------
    story = []
    story.append(Paragraph(INSTITUTE_NAME, title_style))
    story.append(Paragraph(INSTITUTE_SUBTITLE, subtitle_style))

    # ---------- Report Meta ----------
    generated_at = timezone.localtime().strftime('%d %b %Y · %H:%M')
    story.append(Paragraph(
        f"<b>Collection Report</b> · {report_meta.get('range_label', '')}",
        meta_style,
    ))
    story.append(Paragraph(
        f"Generated by <b>{report_meta.get('generated_by', '—')}</b> on {generated_at} "
        f"· {report_meta.get('count', 0)} transaction(s) "
        f"· Total <b>Rs. {_format_amount(report_meta.get('total', Decimal('0.00')))}</b>",
        meta_style,
    ))
    story.append(Spacer(1, 8))

    # ---------- Table ----------
    headers = [
        'Txn ID', 'Student ID', 'Student Name', 'Course / Batch',
        'Fee Category', 'Month', 'Amount (Rs.)', 'Payment Date', 'Method', 'Received By',
    ]

    data = [headers]
    for r in rows:
        payment_date_local = timezone.localtime(r['payment_date']) if r['payment_date'] else None
        payment_date_str = payment_date_local.strftime('%d %b %y %H:%M') if payment_date_local else ''

        # Combine course/batch into one cell to save width
        course_batch = f"{r['course_code']} · {r['batch_name']}"
        # Use Paragraphs for wrapping in name/category columns
        data.append([
            Paragraph(r['transaction_id'][-12:], small_style),  # txn (short)
            Paragraph(r['student_id'], small_style),
            Paragraph(_escape_xml(r['student_name']), small_style),
            Paragraph(_escape_xml(course_batch), small_style),
            Paragraph(_escape_xml(r['fee_category']), small_style),
            Paragraph(r['obligation_month'] or '—', small_style),
            _format_amount(r['amount']),
            Paragraph(payment_date_str, small_style),
            Paragraph(r['payment_method_label'], small_style),
            Paragraph(_escape_xml(r['received_by']), small_style),
        ])

    # Column widths for landscape A4 (267mm usable ≈ 757pt)
    col_widths = [
        60,   # txn
        55,   # student id
        85,   # name
        100,  # course/batch
        65,   # fee category
        50,   # month
        60,   # amount
        65,   # payment date
        55,   # method
        80,   # received by
    ]

    table = Table(data, colWidths=col_widths, repeatRows=1)
    table.setStyle(TableStyle([
        # Header
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#0B1736')),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, 0), 8),
        ('ALIGN', (0, 0), (-1, 0), 'CENTER'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 6),
        ('TOPPADDING', (0, 0), (-1, 0), 6),

        # Body
        ('FONTSIZE', (0, 1), (-1, -1), 7),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#F8FAFC')]),
        ('GRID', (0, 0), (-1, -1), 0.25, colors.HexColor('#E5E9F2')),
        ('LEFTPADDING', (0, 0), (-1, -1), 4),
        ('RIGHTPADDING', (0, 0), (-1, -1), 4),
        ('TOPPADDING', (0, 1), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 1), (-1, -1), 4),

        # Amount column alignment
        ('ALIGN', (6, 1), (6, -1), 'RIGHT'),
    ]))

    story.append(table)

    # ---------- Totals ----------
    story.append(Spacer(1, 8))
    totals_data = [[
        Paragraph(
            f"<b>TOTAL: Rs. {_format_amount(report_meta.get('total', Decimal('0.00')))}</b> "
            f"· {report_meta.get('count', 0)} transaction(s)",
            ParagraphStyle(
                'TotalStyle',
                parent=styles['Normal'],
                fontSize=11,
                textColor=colors.HexColor('#0B1736'),
            ),
        )
    ]]
    totals_table = Table(totals_data, colWidths=[sum(col_widths)])
    totals_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#EFF6FF')),
        ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#2563EB')),
        ('ALIGN', (0, 0), (-1, -1), 'RIGHT'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 8),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
        ('RIGHTPADDING', (0, 0), (-1, -1), 12),
    ]))
    story.append(totals_table)

    # ---------- Footer ----------
    story.append(Spacer(1, 16))
    story.append(Paragraph(
        f"<i>Confidential — {INSTITUTE_NAME} · {INSTITUTE_ADDRESS}</i>",
        footer_style,
    ))

    # ---------- Build with page number callback ----------
    def _add_page_number(canvas, doc_obj):
        page_num = canvas.getPageNumber()
        text = f"Page {page_num}"
        canvas.saveState()
        canvas.setFont('Helvetica', 8)
        canvas.setFillColor(colors.HexColor('#94A3B8'))
        canvas.drawRightString(
            doc_obj.pagesize[0] - 15 * mm,
            10 * mm,
            text,
        )
        # Footer line
        canvas.drawString(
            15 * mm,
            10 * mm,
            f"{INSTITUTE_NAME} · Collection Report",
        )
        canvas.restoreState()

    doc.build(story, onFirstPage=_add_page_number, onLaterPages=_add_page_number)

    buffer.seek(0)
    return buffer.getvalue()


# ============================================================
# HELPERS
# ============================================================
def _format_amount(value):
    """Format Decimal as '1,234.56'."""
    try:
        d = Decimal(str(value))
    except (ValueError, TypeError):
        d = Decimal('0.00')
    return f"{d:,.2f}"


def _escape_xml(text):
    """
    Escape special chars for ReportLab Paragraph (XML-ish).
    Prevents crashes from user-supplied strings with & < >.
    """
    if not text:
        return ''
    return (
        str(text)
        .replace('&', '&amp;')
        .replace('<', '&lt;')
        .replace('>', '&gt;')
    )