"""
Export generators for the reports application.

Two functions:
    generate_excel_report(rows, report_meta) -> bytes
    generate_pdf_report(rows, report_meta)   -> bytes

Both accept:
    rows:        list of dicts from reports.services.get_report_rows_for_export
    report_meta: dict with keys:
                    - range_label (str)
                    - total (Decimal)
                    - count (int)
                    - generated_by (str)

Returns in-memory bytes suitable for HttpResponse.
"""
import io
from datetime import datetime
from decimal import Decimal

from django.utils import timezone


# ============================================================
# CONSTANTS
# ============================================================
INSTITUTE_NAME = 'EASYTECH THATTA'
INSTITUTE_SUBTITLE = 'Institute Management System'
INSTITUTE_ADDRESS = 'Thatta, Sindh, Pakistan'


# ============================================================
# EXCEL EXPORT (OpenPyXL)
# ============================================================
def generate_excel_report(rows, report_meta):
    """
    Generate a styled Excel workbook for a collection report.

    Returns bytes of .xlsx file.
    """
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
    from openpyxl.utils import get_column_letter

    wb = Workbook()
    ws = wb.active
    ws.title = 'Collection Report'

    # ---------- Styles ----------
    header_font = Font(bold=True, color='FFFFFF', size=12)
    header_fill = PatternFill(start_color='0B1736', end_color='0B1736', fill_type='solid')

    subtitle_font = Font(bold=True, size=14, color='0B1736')
    meta_font = Font(size=10, color='64748B')

    table_header_font = Font(bold=True, color='FFFFFF', size=10)
    table_header_fill = PatternFill(start_color='2563EB', end_color='2563EB', fill_type='solid')

    total_font = Font(bold=True, size=11, color='0B1736')
    total_fill = PatternFill(start_color='EFF6FF', end_color='EFF6FF', fill_type='solid')

    thin_border = Border(
        left=Side(style='thin', color='E5E9F2'),
        right=Side(style='thin', color='E5E9F2'),
        top=Side(style='thin', color='E5E9F2'),
        bottom=Side(style='thin', color='E5E9F2'),
    )

    center = Alignment(horizontal='center', vertical='center')
    left = Alignment(horizontal='left', vertical='center')
    right = Alignment(horizontal='right', vertical='center')

    # ---------- Header Banner ----------
    ws.merge_cells('A1:L1')
    cell = ws['A1']
    cell.value = INSTITUTE_NAME
    cell.font = header_font
    cell.fill = header_fill
    cell.alignment = center
    ws.row_dimensions[1].height = 28

    ws.merge_cells('A2:L2')
    ws['A2'].value = 'Collection Report'
    ws['A2'].font = subtitle_font
    ws['A2'].alignment = center

    # ---------- Metadata ----------
    ws.merge_cells('A3:L3')
    ws['A3'].value = f"Date Range: {report_meta.get('range_label', '')}"
    ws['A3'].font = meta_font
    ws['A3'].alignment = center

    ws.merge_cells('A4:L4')
    generated_at = timezone.localtime().strftime('%d %b %Y · %H:%M')
    ws['A4'].value = (
        f"Generated by: {report_meta.get('generated_by', '—')} "
        f"· {generated_at} "
        f"· Transactions: {report_meta.get('count', 0)}"
    )
    ws['A4'].font = meta_font
    ws['A4'].alignment = center

    # Blank spacer row
    ws.row_dimensions[5].height = 8

    # ---------- Table Header (row 6) ----------
    headers = [
        'Txn ID', 'Student ID', 'Student Name', 'Father Name',
        'Course', 'Batch', 'Fee Category', 'Month',
        'Amount (Rs.)', 'Payment Date', 'Method', 'Received By',
    ]
    header_row = 6
    for col_idx, header in enumerate(headers, start=1):
        cell = ws.cell(row=header_row, column=col_idx, value=header)
        cell.font = table_header_font
        cell.fill = table_header_fill
        cell.alignment = center
        cell.border = thin_border
    ws.row_dimensions[header_row].height = 24

    # ---------- Data Rows ----------
    data_start_row = 7
    for row_offset, r in enumerate(rows):
        row_num = data_start_row + row_offset

        payment_date_local = timezone.localtime(r['payment_date']) if r['payment_date'] else None
        payment_date_str = payment_date_local.strftime('%d %b %Y %H:%M') if payment_date_local else ''

        values = [
            r['transaction_id'],
            r['student_id'],
            r['student_name'],
            r['father_name'],
            f"{r['course_code']} — {r['course_name']}",
            r['batch_name'],
            r['fee_category'],
            r['obligation_month'] or '—',
            float(r['amount']),
            payment_date_str,
            r['payment_method_label'],
            r['received_by'],
        ]

        for col_idx, value in enumerate(values, start=1):
            cell = ws.cell(row=row_num, column=col_idx, value=value)
            cell.border = thin_border
            cell.alignment = left if col_idx in (3, 4, 5, 6, 7, 12) else center
            if col_idx == 9:  # Amount
                cell.number_format = '#,##0.00'
                cell.alignment = right

    # ---------- Totals Row ----------
    totals_row = data_start_row + len(rows)
    ws.merge_cells(start_row=totals_row, start_column=1, end_row=totals_row, end_column=8)
    ws.cell(row=totals_row, column=1, value='TOTAL').font = total_font
    ws.cell(row=totals_row, column=1).fill = total_fill
    ws.cell(row=totals_row, column=1).alignment = right

    amount_cell = ws.cell(row=totals_row, column=9, value=float(report_meta.get('total', Decimal('0.00'))))
    amount_cell.font = total_font
    amount_cell.fill = total_fill
    amount_cell.number_format = '#,##0.00'
    amount_cell.alignment = right

    ws.merge_cells(start_row=totals_row, start_column=10, end_row=totals_row, end_column=12)
    ws.cell(row=totals_row, column=10, value=f"{report_meta.get('count', 0)} transactions").font = total_font
    ws.cell(row=totals_row, column=10).fill = total_fill

    for col_idx in range(1, 13):
        ws.cell(row=totals_row, column=col_idx).border = thin_border

    # ---------- Auto Column Widths ----------
    # Base widths per column (in characters) — will expand for long values
    base_widths = [22, 14, 22, 22, 26, 20, 20, 12, 14, 20, 16, 20]
    for i, w in enumerate(base_widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w

    # ---------- Freeze Panes ----------
    ws.freeze_panes = 'A7'  # Freeze everything above the data rows

    # ---------- Save to BytesIO ----------
    buffer = io.BytesIO()
    wb.save(buffer)
    buffer.seek(0)
    return buffer.getvalue()


